"""
evaluation.py
Phase 4: Self-Evaluation with Expert Criteria.

Implements the 7-dimension evaluation framework from the ACL 2025 paper:
"My Climate CoPilot: A Question Answering System for Climate Adaptation in Agriculture"

Each dimension has 3 sub-criteria scored as 0 or 1, giving a total of 21 points possible.
The LLM evaluates the generated response in a separate conversation for objectivity.
"""

import os
import json
from pathlib import Path
from typing import Dict, Any, Optional, List

from groq import Groq
from dotenv import load_dotenv

# Accept standard UTF-8 .env files and UTF-16 files saved by Windows Notepad.
_ENV_PATH = Path(__file__).resolve().parent / ".env"
try:
    load_dotenv(_ENV_PATH, encoding="utf-8")
except UnicodeDecodeError:
    load_dotenv(_ENV_PATH, encoding="utf-16")

# Evaluation model (can be different from generation model)
EVAL_MODEL = "llama-3.3-70b-versatile"

# The 7 evaluation dimensions with sub-criteria (from the paper)
EVALUATION_CRITERIA = {
    "1_context": {
        "name": "Context",
        "subcriteria": {
            "1a": "Attempts to give some broader context to explain the issue",
            "1b": "Provides an introductory paragraph to introduce the topic",
            "1c": "Provides a summary paragraph at the end"
        }
    },
    "2_structure": {
        "name": "Structure",
        "subcriteria": {
            "2a": "Overall response is well structured, easy to read",
            "2b": "Headings and subheadings are well structured and logical, with appropriate categories",
            "2c": "Dot points or bullet points are used appropriately"
        }
    },
    "3_language": {
        "name": "Use of Language",
        "subcriteria": {
            "3a": "Phrasing is appropriate (easy to read, fluent) and not awkward or incorrect",
            "3b": "Correct use of grammar",
            "3c": "Consistent with language used within the climate/agriculture industry"
        }
    },
    "4_citations": {
        "name": "Use of Citations",
        "subcriteria": {
            "4a": "Citations are used appropriately",
            "4b": "The number of citations used is appropriate",
            "4c": "Citations are easy to read and follow"
        }
    },
    "5_specificity": {
        "name": "Specificity",
        "subcriteria": {
            "5a": "Gives information which is specific to a commodity, if appropriate",
            "5b": "Gives information which is specific to the location/region in question, where applicable",
            "5c": "Where there is no information specific to a location, the system admits this"
        }
    },
    "6_comprehensiveness": {
        "name": "Comprehensiveness",
        "subcriteria": {
            "6a": "The response is comprehensive and does not just give a partial, incomplete answer",
            "6b": "Shows depth of knowledge or understanding regarding the topic",
            "6c": "Answers beyond the question's scope to provide helpful context"
        }
    },
    "7_accuracy": {
        "name": "Scientific Accuracy",
        "subcriteria": {
            "7a": "The information appears scientifically robust",
            "7b": "The response meets scientific expectations based on the provided sources",
            "7c": "The response does not contain obvious errors or contradictions"
        }
    }
}


def _get_groq_client() -> Groq:
    """Initialize and return Groq client."""
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        raise ValueError("GROQ_API_KEY not found in environment variables.")
    return Groq(api_key=api_key)


def _build_evaluation_prompt(question: str, answer: str, passages: List[Dict[str, Any]]) -> str:
    """Build the evaluation prompt with criteria."""
    
    # Format passages for context
    passages_text = ""
    for i, p in enumerate(passages, 1):
        passages_text += f"[{i}] Source: {p['source']} | Document: {p['title']} | Page: {p['page_number']}\n"
        passages_text += f"{p['text']}\n\n"
    
    # Build criteria list
    criteria_text = ""
    for dim_key, dim_data in EVALUATION_CRITERIA.items():
        criteria_text += f"\n### {dim_data['name']}\n"
        for sub_key, sub_desc in dim_data['subcriteria'].items():
            criteria_text += f"- {sub_key}: {sub_desc}\n"
    
    return f"""You are an expert evaluator for climate science question-answering systems.

Your task is to evaluate a response generated by a climate QA system. Score each criterion as either 1 (met) or 0 (not met).

=== ORIGINAL QUESTION ===
{question}

=== SOURCE PASSAGES PROVIDED TO THE SYSTEM ===
{passages_text}

=== GENERATED RESPONSE TO EVALUATE ===
{answer}

=== EVALUATION CRITERIA ===
{criteria_text}

=== INSTRUCTIONS ===
For each criterion, determine if it is met (1) or not met (0).
Provide your evaluation as a JSON object with the following structure:

{{
    "scores": {{
        "1a": 0 or 1,
        "1b": 0 or 1,
        "1c": 0 or 1,
        "2a": 0 or 1,
        "2b": 0 or 1,
        "2c": 0 or 1,
        "3a": 0 or 1,
        "3b": 0 or 1,
        "3c": 0 or 1,
        "4a": 0 or 1,
        "4b": 0 or 1,
        "4c": 0 or 1,
        "5a": 0 or 1,
        "5b": 0 or 1,
        "5c": 0 or 1,
        "6a": 0 or 1,
        "6b": 0 or 1,
        "6c": 0 or 1,
        "7a": 0 or 1,
        "7b": 0 or 1,
        "7c": 0 or 1
    }},
    "feedback": "Brief overall feedback explaining the evaluation (2-3 sentences)"
}}

Return ONLY the JSON object, no other text."""


def _parse_evaluation_response(response_text: str) -> Dict[str, Any]:
    """Parse the LLM evaluation response into structured data."""
    try:
        # Try to extract JSON from the response
        # Handle cases where LLM might add markdown code blocks
        text = response_text.strip()
        if text.startswith("```"):
            # Remove markdown code block
            lines = text.split("\n")
            text = "\n".join(lines[1:-1] if lines[-1] == "```" else lines[1:])
        
        return json.loads(text)
    except json.JSONDecodeError:
        # If parsing fails, return empty scores
        return {
            "scores": {},
            "feedback": "Evaluation parsing failed. Raw response: " + response_text[:500],
            "error": True
        }


def evaluate_response(
    question: str,
    answer: str,
    passages: List[Dict[str, Any]],
    model: str = EVAL_MODEL,
    verbose: bool = False
) -> Dict[str, Any]:
    """
    Evaluate a generated answer using the 7-dimension expert criteria.
    
    Args:
        question: The original user question
        answer: The generated answer to evaluate
        passages: List of retrieved passages used for generation
        model: Groq model for evaluation
        verbose: Print progress
    
    Returns:
        Dict with dimension scores, sub-scores, total score, and feedback
    """
    if verbose:
        print(f"[EVAL] Evaluating response with {model}...")
    
    client = _get_groq_client()
    prompt = _build_evaluation_prompt(question, answer, passages)
    
    completion = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "user", "content": prompt}
        ],
        temperature=0.1,  # Low temperature for consistent evaluation
        max_tokens=1024,
        top_p=1,
        stream=False
    )
    
    raw_response = completion.choices[0].message.content
    parsed = _parse_evaluation_response(raw_response)
    
    if parsed.get("error"):
        return parsed
    
    scores = parsed.get("scores", {})
    
    # Calculate dimension scores (each dimension has 3 sub-criteria)
    dimension_scores = {}
    for dim_key, dim_data in EVALUATION_CRITERIA.items():
        dim_num = dim_key.split("_")[0]
        sub_scores = [scores.get(f"{dim_num}{c}", 0) for c in ["a", "b", "c"]]
        dimension_scores[dim_data["name"]] = {
            "score": sum(sub_scores),
            "max": 3,
            "subscores": {
                f"{dim_num}a": scores.get(f"{dim_num}a", 0),
                f"{dim_num}b": scores.get(f"{dim_num}b", 0),
                f"{dim_num}c": scores.get(f"{dim_num}c", 0)
            }
        }
    
    # Calculate total score
    total_score = sum(d["score"] for d in dimension_scores.values())
    max_score = 21  # 7 dimensions × 3 sub-criteria
    
    result = {
        "total_score": total_score,
        "max_score": max_score,
        "percentage": round((total_score / max_score) * 100, 1),
        "dimensions": dimension_scores,
        "feedback": parsed.get("feedback", ""),
        "model": model,
        "usage": {
            "prompt_tokens": completion.usage.prompt_tokens,
            "completion_tokens": completion.usage.completion_tokens,
            "total_tokens": completion.usage.total_tokens
        }
    }
    
    if verbose:
        print(f"[EVAL] Evaluation complete. Score: {total_score}/{max_score} ({result['percentage']}%)")
    
    return result


def print_evaluation(eval_result: Dict[str, Any]) -> None:
    """Pretty print the evaluation results."""
    
    if eval_result.get("error"):
        print("\n⚠️  Evaluation Error:")
        print(eval_result.get("feedback", "Unknown error"))
        return
    
    print("\n" + "=" * 70)
    print(" SELF-EVALUATION (7 Expert Dimensions)")
    print("=" * 70)
    
    # Overall score
    score = eval_result["total_score"]
    max_score = eval_result["max_score"]
    pct = eval_result["percentage"]
    
    # Score bar visualization
    filled = int(pct / 5)  # 20 chars for 100%
    bar = "█" * filled + "░" * (20 - filled)
    
    print(f"\n📊 Overall Score: {score}/{max_score} ({pct}%)")
    print(f"   [{bar}]")
    
    # Dimension breakdown
    print("\n📋 Dimension Breakdown:")
    print("-" * 50)
    
    for dim_name, dim_data in eval_result["dimensions"].items():
        dim_score = dim_data["score"]
        dim_max = dim_data["max"]
        status = "✅" if dim_score == dim_max else ("⚠️" if dim_score >= 2 else "❌")
        
        # Sub-criteria
        subs = dim_data["subscores"]
        sub_str = " ".join([f"{'✓' if v else '✗'}" for v in subs.values()])
        
        print(f"  {status} {dim_name}: {dim_score}/{dim_max}  [{sub_str}]")
    
    # Feedback
    print("\n" + "-" * 50)
    print(f"💬 Feedback: {eval_result['feedback']}")
    
    # Token usage
    usage = eval_result.get("usage", {})
    if usage:
        print(f"\n📈 Eval Tokens: {usage.get('total_tokens', 0)}")
    
    print("=" * 70 + "\n")


def get_evaluation_summary(eval_result: Dict[str, Any]) -> str:
    """Get a one-line summary of the evaluation."""
    if eval_result.get("error"):
        return "Evaluation failed"
    
    score = eval_result["total_score"]
    max_score = eval_result["max_score"]
    pct = eval_result["percentage"]
    
    # Determine grade
    if pct >= 90:
        grade = "Excellent"
    elif pct >= 75:
        grade = "Good"
    elif pct >= 60:
        grade = "Adequate"
    elif pct >= 40:
        grade = "Needs Improvement"
    else:
        grade = "Poor"
    
    return f"{score}/{max_score} ({pct}%) - {grade}"


